import { test, expect, finishAdminMfa, accountOption } from './fixtures';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { php, phpEnv } from '../scripts/php-runtime.mjs';

test('email and policies allow reporting without an ID; optional review earns a revocable profile badge', async ({ page, browser, request }) => {
  test.setTimeout(120000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const email = `verification-${Date.now()}@example.test`;
  await page.goto('/'); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  const auth = page.getByRole('dialog', { name: 'Welcome to your community', exact: true });
  await auth.getByRole('button', { name: 'Create an account', exact: true }).click();
  await auth.getByLabel('Full name').fill('Synthetic Identity Applicant');
  await auth.getByLabel('Email address').fill(email);
  await auth.getByLabel('Password', { exact: true }).fill('synthetic-verification-password');
  await auth.getByRole('button', { name: 'Create your account', exact: true }).click();
  await expect(auth.getByRole('checkbox', { name: 'I agree to the terms and conditions and acknowledge the privacy notice.' })).toBeFocused();
  await auth.getByText('Privacy notice', { exact: true }).click();
  await expect(auth).toContainText('BASISTA MUNICIPAL HALL');
  await auth.getByRole('checkbox', { name: 'I agree to the terms and conditions and acknowledge the privacy notice.' }).check();
  await auth.getByRole('button', { name: 'Create your account', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Reporter verification', exact: true });
  await expect(panel).toContainText('Your email is not verified');
  await page.getByRole('button', { name: 'Report a hazard', exact: true }).click();
  await page.getByRole('dialog', { name: 'Before you report', exact: true }).getByRole('button', { name: 'No, continue to the report', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Report a hazard', exact: true })).toHaveCount(0);
  // Read a synthetic queued link only inside the isolated browser database;
  // consume through the real endpoint. This does not assert SMTP delivery.
  const code = `require 'vendor/autoload.php'; $app = require 'bootstrap/app.php'; $app->make(Illuminate\\Contracts\\Console\\Kernel::class)->bootstrap(); $driver=config('database.default'); $db=config('database.connections.'.$driver.'.database'); if (!app()->environment('testing') || !(($driver==='sqlite' && str_replace('\\\\','/',$db)===str_replace('\\\\','/',dirname(base_path()).'/.cache/e2e.sqlite')) || ($driver==='mysql' && $db==='municipal_hazards_e2e'))) exit(2); $user=App\\Models\\User::where('email',getenv('E2E_VERIFY_EMAIL'))->firstOrFail(); $row=Illuminate\\Support\\Facades\\DB::table('security_challenges')->where('user_id',$user->id)->where('purpose','verify')->where('consumed',false)->first(); echo $row->id.'.'.Illuminate\\Support\\Facades\\Crypt::decryptString($row->payload);`;
  const proof = spawnSync(php, ['-r', code], { cwd: resolve(__dirname, '../hazard-server'), env: { ...phpEnv(), E2E_VERIFY_EMAIL: email }, encoding: 'utf8', windowsHide: true });
  expect(proof.status).toBe(0);
  const origin = `http://127.0.0.1:${process.env.HAZARD_API_PORT || '18000'}`;
  const consumed = await request.post(`${origin}/api/auth/recovery/consume`, { data: { token: proof.stdout.trim(), purpose: 'verify' } });
  expect(consumed.status()).toBe(200);
  await panel.getByRole('button', { name: 'Refresh verification status', exact: true }).click();
  await expect(panel).toContainText('Email verified.');
  await expect(panel).toContainText('You are ready to report.');
  await page.getByRole('button', { name: 'Report a hazard', exact: true }).click();
  await page.getByRole('dialog', { name: 'Before you report', exact: true }).getByRole('button', { name: 'No, continue to the report', exact: true }).click();
  const reportForm = page.getByRole('dialog', { name: 'Report a hazard', exact: true });
  await expect(reportForm).toBeVisible();
  await reportForm.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.getByRole('dialog', { name: 'Discard this report?', exact: true }).getByRole('button', { name: 'Discard report', exact: true }).click();
  await accountOption(page, 'My profile');
  await expect(page.getByRole('img', { name: 'Identity verified', exact: true })).toHaveCount(0);
  await accountOption(page, 'Settings');
  for (const width of [1280, 375]) {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await panel.screenshot({ path: `test-results/reporter-verification-${width}.png`, animations: 'disabled' });
  }
  const bytes = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 2500; canvas.height = 1400; const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, 2500, 1400); ctx.fillStyle = '#000'; ctx.font = '32px sans-serif'; ctx.fillText('SYNTHETIC TEST DOCUMENT', 30, 70); ctx.fillText('Synthetic Identity Applicant', 30, 130); ctx.fillRect(30, 190, 160, 160); return canvas.toDataURL('image/png').split(',')[1]!; });
  await panel.getByLabel('One redacted government-ID image').setInputFiles({ name: 'synthetic-id.png', mimeType: 'image/png', buffer: Buffer.from(bytes, 'base64') });
  const consent = panel.getByRole('checkbox', { name: /I consent to the operator processing this ID image/ });
  expect(await consent.locator('..').evaluate(label => parseFloat(getComputedStyle(label).fontSize))).toBeGreaterThanOrEqual(16);
  await consent.check();
  await panel.getByRole('button', { name: 'Submit ID for private review', exact: true }).click();
  await expect(panel).toContainText('Awaiting administrator review');
  const context = await browser.newContext(); const admin = await context.newPage();
  await admin.goto('/'); await admin.getByRole('button', { name: 'Sign in', exact: true }).click();
  const login = admin.getByRole('dialog', { name: 'Welcome to your community', exact: true });
  await login.getByLabel('Email address').fill('admin@munialert.test'); await login.getByLabel('Password', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD!); await login.getByRole('button', { name: 'Sign in', exact: true }).click(); await finishAdminMfa(admin);
  await accountOption(admin, 'Settings');
  await admin.locator('.identity-review tr').filter({ hasText: 'Synthetic Identity Applicant' }).getByRole('button', { name: 'Review ID', exact: true }).click();
  const review = admin.getByRole('dialog', { name: 'Private government-ID review', exact: true });
  await expect.poll(() => review.locator('img').evaluate((img: HTMLImageElement) => img.naturalWidth > 0)).toBe(true);
  expect(await review.locator('img').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeLessThanOrEqual(1920);
  await review.screenshot({ path: 'test-results/identity-review-desktop.png', animations: 'disabled' });
  await review.getByRole('checkbox', { name: /I reviewed the document and account name/ }).check();
  await review.getByRole('button', { name: 'Save identity decision', exact: true }).click();
  await expect(review).toHaveCount(0); await context.close();
  await panel.getByRole('button', { name: 'Refresh verification status', exact: true }).click();
  await expect(panel).toContainText('You are ready to report.');
  await accountOption(page, 'My profile');
  await expect(page.locator('.profile-identity').getByRole('img', { name: 'Identity verified', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/verified-profile-phone.png', fullPage: true });
  await accountOption(page, 'Settings');
  await panel.getByRole('button', { name: 'Withdraw identity verification', exact: true }).click();
  await expect(panel).toContainText('You are ready to report.');
  await accountOption(page, 'My profile');
  await expect(page.locator('.profile-identity').getByRole('img', { name: 'Identity verified', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Report a hazard', exact: true }).click();
  await page.getByRole('dialog', { name: 'Before you report', exact: true }).getByRole('button', { name: 'No, continue to the report', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Report a hazard', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
